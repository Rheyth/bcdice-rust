/// クリティカル表の項目。Ruby の `[上限値, 内容]`。
type CriticalTableItem = (i64, &'static str);

/// Ruby `Warhammer4::CriticalTable` と `Warhammer4::CriticalTable_UIA`。
///
/// どちらも「1D100の出目を補正し、`上限値 >= 出目` になる最初の項目を選ぶ」表で、
/// 補正の内容だけが違う（[`roll`](Self::roll) / [`roll_uia`](Self::roll_uia)）。
/// 表の形も出力の整形も同じなので、Rustでは1つの型にまとめた。
struct CriticalTable {
    /// Ruby `@name`
    name: &'static str,
    /// Ruby `@items`
    items: &'static [CriticalTableItem],
}

impl CriticalTable {
    /// Ruby `@items.find { |key, _| key >= dice }[1]`。
    ///
    /// Ruby は該当なしで `NoMethodError` になるが、呼び出し側が出目を表の範囲へ
    /// clamp しているので到達しない。`RangeTable::fetch` と同じく空文字列に倒す。
    fn fetch(&self, dice: i64) -> &'static str {
        self.items
            .iter()
            .find(|(key, _)| *key >= dice)
            .map(|(_, content)| *content)
            .unwrap_or("")
    }

    /// Ruby `CriticalTable#roll(randomizer, under_ganken_bonus)`。
    fn roll(&self, rng: &mut Randomizer, under_ganken_bonus: bool) -> Result<String, EvalError> {
        let mut dice = rng.roll_once(100)?;
        if under_ganken_bonus {
            dice = (dice - 20).clamp(1, 100);
        }
        Ok(format!("{}({}) ＞ {}", self.name, dice, self.fetch(dice)))
    }

    /// Ruby `CriticalTable_UIA#roll(randomizer, over_damage)`。
    ///
    /// Ruby の `if over_damage` は `0` も真なので補正は常に走る（`+0` で実質無補正）。
    fn roll_uia(&self, rng: &mut Randomizer, over_damage: i64) -> Result<String, EvalError> {
        let dice = rng
            .roll_once(100)?
            .saturating_add(over_damage.saturating_mul(10))
            .clamp(1, 1000);
        Ok(format!("{}({}) ＞ {}", self.name, dice, self.fetch(dice)))
    }
}

/// Ruby `CRITICAL_TABLES[part]`。`part` は `T` を `B` に読み替え済み。
fn critical_table(part: &str) -> &'static CriticalTable {
    match part {
        "H" => &CT_HEAD,
        "A" => &CT_ARM,
        "L" => &CT_LEG,
        // 正規表現の文字クラスが `[HABTL]` なので、残るのは `B`（と読み替え済みの `T`）
        _ => &CT_BODY,
    }
}

/// Ruby `CRITICAL_TABLES_UIA[part]`。`part` は `T` を `B` に読み替え済み。
fn critical_table_uia(part: &str) -> &'static CriticalTable {
    match part {
        "H" => &BKCT_HEAD,
        "A" => &BKCT_ARM,
        "L" => &BKCT_LEG,
        _ => &BKCT_BODY,
    }
}

