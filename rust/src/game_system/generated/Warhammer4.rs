    /// Ruby `RangeTable#store` が構築時に行う検査（隙間・重なり・端の被覆）。
    ///
    /// Ruby はクラス定数の構築時に落ちるので、機械変換した表データの取りこぼしは
    /// ここで押さえる。
    #[test]
    fn range_tables_are_complete() {
        assert_eq!(HIT_PARTS_TABLE.validate(), Ok(()), "命中部位表");
        assert_eq!(WRATH_OF_GOD_TABLE.validate(), Ok(()), "神々の天罰表");
        for (name, table) in TABLES {
            assert_eq!(table.validate(), Ok(()), "{name}");
        }
    }

    /// クリティカル表が clamp 後の出目を全域で引けること。
    ///
    /// Ruby の `@items.find { |key, _| key >= dice }` は該当なしで `NoMethodError`
    /// になるので、`CriticalTable::fetch` の空文字列フォールバックは到達しない。
    /// 機械変換した表データがその前提を保っていることを確かめる。
    #[test]
    fn critical_tables_cover_clamped_dice() {
        for (table, max_dice) in [
            (&CT_HEAD, 100),
            (&CT_ARM, 100),
            (&CT_BODY, 100),
            (&CT_LEG, 100),
            (&BKCT_HEAD, 1000),
            (&BKCT_ARM, 1000),
            (&BKCT_BODY, 1000),
            (&BKCT_LEG, 1000),
        ] {
            for dice in 1..=max_dice {
                assert!(
                    !table.fetch(dice).is_empty(),
                    "{}: 出目 {dice} で項目が引けない",
                    table.name
                );
            }
        }
    }

    fn toml_path() -> Option<PathBuf> {
        let path = Path::new(env!("CARGO_MANIFEST_DIR"))
            .parent()?
            .join("test/data/Warhammer4.toml");
        path.exists().then_some(path)
    }

    /// Ruby `part = "B" if part == "T"`（胴体の別表記。TOML にケースが無い分岐）。
    #[test]
    fn body_part_alias_t_is_same_as_b() {
        for (t_command, b_command) in [("WHCTT", "WHCTB"), ("BKCTT", "BKCTB")] {
            let eval = |command: &str| {
                let mut src = SeededRandomizer::new(vec![(50, 100)]);
                let result = eval_command(&GameSystemId::new("Warhammer4"), command, &mut src)
                    .expect("eval")
                    .expect("output");
                assert!(src.is_empty(), "{command}: unconsumed rands");
                result.text
            };
            let text = eval(t_command);
            assert_eq!(text, eval(b_command), "{t_command} と {b_command}");
            assert!(text.starts_with("胴体CT表"), "{t_command}: {text}");
        }
    }

    fn check_flag(reasons: &mut Vec<String>, name: &str, expected: bool, actual: bool) {
        if expected != actual {
            reasons.push(format!(
                "{name} flag mismatch: expected {expected}, actual {actual}"
            ));
        }
    }

    /// `test/data/Warhammer4.toml` の全ケースが通ること。
    ///
    /// 判定項目は `rust/tests/toml_harness.rs::run_case` と同じ
    /// （出力文字列・5フラグ・注入乱数を使い切ったか）。本体のハーネスは
    /// まだ DiceBot しか assert していないので、移植したシステムの回帰は
    /// ここで押さえる。
    #[test]
    fn all_toml_cases_pass() {
        let Some(path) = toml_path() else {
            // worktree外でクレート単体ビルドされた場合
            eprintln!("skip: test/data/Warhammer4.toml not found");
            return;
        };

        let data = TestDataFile::load(&path).expect("Warhammer4.toml must parse");
        assert_eq!(
            data.tests.len(),
            246,
            "case count in test/data/Warhammer4.toml"
        );

        let mut failures: Vec<String> = Vec::new();
        for (i, tc) in data.tests.iter().enumerate() {
            assert_eq!(
                tc.game_system, "Warhammer4",
                "unexpected game system in Warhammer4.toml"
            );

            let mut reasons: Vec<String> = Vec::new();
            let rands: Vec<(i64, i64)> = tc.rands.iter().map(|r| (r.value, r.sides)).collect();
            let mut src = SeededRandomizer::new(rands);

            match eval_command(&GameSystemId::new("Warhammer4"), &tc.input, &mut src) {
                Err(e) => reasons.push(format!("eval error: {e}")),
                Ok(None) => {
                    if !tc.expects_nil() {
                        reasons.push(format!(
                            "eval returned nil, but output was expected: {:?}",
                            tc.output
                        ));
                    }
                }
                Ok(Some(result)) => {
                    if tc.expects_nil() {
                        reasons.push(format!("expected nil output, got {:?}", result.text));
                    } else if result.text != tc.output {
                        reasons.push(format!(
                            "output mismatch\n    expected: {:?}\n    actual:   {:?}",
                            tc.output, result.text
                        ));
                    }
                    check_flag(&mut reasons, "secret", tc.secret, result.secret);
                    check_flag(&mut reasons, "success", tc.success, result.success);
                    check_flag(&mut reasons, "failure", tc.failure, result.failure);
                    check_flag(&mut reasons, "critical", tc.critical, result.critical);
                    check_flag(&mut reasons, "fumble", tc.fumble, result.fumble);
                }
            }

            if !src.is_empty() {
                reasons.push(format!("unconsumed rands remain ({})", src.remaining()));
            }

            if !reasons.is_empty() {
                failures.push(format!(
                    "FAIL Warhammer4:{}:{}\n  - {}",
                    i + 1,
                    tc.input,
                    reasons.join("\n  - ")
                ));
            }
        }

        assert!(
            failures.is_empty(),
            "{}/{} Warhammer4 cases failed:\n{}",
            failures.len(),
            data.tests.len(),
            failures.join("\n")
        );
    }
