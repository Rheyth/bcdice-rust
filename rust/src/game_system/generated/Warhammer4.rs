/// Ruby `Warhammer4#roll_critical_table`。
fn roll_critical_table(command: &str, rng: &mut Randomizer) -> Result<Option<String>, EvalError> {
    static WHCT: OnceLock<Regex> = OnceLock::new();
    static BKCT: OnceLock<Regex> = OnceLock::new();
    let whct = WHCT.get_or_init(|| Regex::new(r"^WHCT([HABTL])(U)?$").expect("valid regex"));
    let bkct = BKCT.get_or_init(|| Regex::new(r"^BKCT([HABTL])(\d*)$").expect("valid regex"));

    if let Some(caps) = whct.captures(command) {
        // Ruby: part = "B" if part == "T"
        let part = normalize_part(&caps[1]);
        let under_ganken_bonus = caps.get(2).is_some();
        return Ok(Some(critical_table(part).roll(rng, under_ganken_bonus)?));
    }

    if let Some(caps) = bkct.captures(command) {
        let part = normalize_part(&caps[1]);
        // Ruby の `(\d*)?` は空文字にもマッチするので nil にならず、`"".to_i == 0`
        let over_damage = parse_i64_or_zero(&caps[2]);
        return Ok(Some(critical_table_uia(part).roll_uia(rng, over_damage)?));
    }

    Ok(None)
}

/// Ruby `part = "B" if part == "T"`（胴体の別表記）。
fn normalize_part(part: &str) -> &str {
    if part == "T" {
        "B"
    } else {
        part
    }
}

/// Ruby `String#to_i`（空文字は 0、桁あふれは i64 に飽和させる）。
fn parse_i64_or_zero(digits: &str) -> i64 {
    if digits.is_empty() {
        0
    } else {
        digits.parse::<i64>().unwrap_or(i64::MAX)
    }
}

/// Ruby `Warhammer4#roll_attack`（命中判定）。
fn roll_attack(command: &str, rng: &mut Randomizer) -> Result<Option<String>, EvalError> {
    static RE: OnceLock<Regex> = OnceLock::new();
    let re = RE.get_or_init(|| Regex::new(r"^WH(\d+)$").expect("valid regex"));

    let Some(caps) = re.captures(command) else {
        return Ok(None);
    };
    let target_number = parse_i64_or_zero(&caps[1]);

    let total = rng.roll_once(100)?;
    // Ruby: result_1d100(total, total, :<=, target_number)&.text
    let result = check_1d100(
        crate::Int::from(total),
        CmpOp::Le,
        crate::Int::from(target_number),
    )
    .map(|r| r.text);

    // Ruby: [..., result, additional_result(...)].compact.join(" ＞ ")
    let mut sequence = vec![format!("({command})"), total.to_string()];
    sequence.extend(result);
    sequence.push(additional_result(total, target_number));

    Ok(Some(sequence.join(" ＞ ")))
}

/// Ruby `Warhammer4#additional_result`。命中部位・クリティカル・ファンブルの表示。
fn additional_result(total: i64, target_number: i64) -> String {
    let (tens, ones) = split_d100(total);
    // Ruby: 一の位と十の位を入れ替えて命中部位表を参照する
    let hit_part = || HIT_PARTS_TABLE.fetch(merge_d100(ones, tens)).unwrap_or("");

    // Ruby: total > 95 は自動失敗時のファンブル処理も拾うため
    if (total > target_number) || (total > 95) {
        if ones == tens {
            "ファンブル".to_owned()
        } else {
            format!("({})", hit_part())
        }
    } else if ones == tens {
        "クリティカル".to_owned()
    } else {
        hit_part().to_owned()
    }
}

/// Ruby `Warhammer4#split_d100`。出目を十の位と一の位へ分ける（100 は `0, 0`）。
fn split_d100(dice: i64) -> (i64, i64) {
    if dice == 100 {
        (0, 0)
    } else {
        (
            sat_i64(&floor_div(crate::Int::from(dice), crate::Int::from(10))),
            dice.rem_euclid(10),
        )
    }
}

/// Ruby `Warhammer4#merge_d100`。十の位と一の位から出目へ戻す（`0, 0` は 100）。
fn merge_d100(tens: i64, ones: i64) -> i64 {
    if tens == 0 && ones == 0 {
        100
    } else {
        tens * 10 + ones
    }
}

/// Ruby `Warhammer4#roll_wrath_of_god_table`（神々の天罰表）。
fn roll_wrath_of_god_table(
    command: &str,
    rng: &mut Randomizer,
) -> Result<Option<String>, EvalError> {
    static RE: OnceLock<Regex> = OnceLock::new();
    let re = RE.get_or_init(|| Regex::new(r"^WHWGT(\d*)$").expect("valid regex"));

    let Some(caps) = re.captures(command) else {
        return Ok(None);
    };
    // Ruby: m[1].to_i（原罪点の省略は 0）
    let sin_point = parse_i64_or_zero(&caps[1]);

    let mut total = rng
        .roll_once(100)?
        .saturating_add(sin_point.saturating_mul(10));
    // Ruby: total = 151 if total > 151
    if total > 151 {
        total = 151;
    }

    Ok(Some(format!(
        "神々の天罰表({total}) ＞ {}",
        WRATH_OF_GOD_TABLE.fetch(total).unwrap_or("")
    )))
}

/// Ruby `Base#roll_tables(command, TABLES)`。
fn roll_tables(command: &str, rng: &mut Randomizer) -> Result<Option<String>, EvalError> {
    let Some((_, table)) = TABLES.iter().find(|(key, _)| *key == command) else {
        return Ok(None);
    };
    Ok(Some(table.roll(rng)?.to_string()))
}

/// Ruby `BCDice::GameSystem::Warhammer4`（ID: `Warhammer4`）。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Warhammer4;

impl GameSystem for Warhammer4 {
    fn id(&self) -> &'static str {
        "Warhammer4"
    }

    fn name(&self) -> &'static str {
        "ウォーハンマーRPG第4版"
    }

    fn sort_key(&self) -> &'static str {
        "うおおはんまあ4"
    }

    fn help_message(&self) -> &'static str {
        HELP_MESSAGE
    }

    fn prefixes(&self) -> &'static [&'static str] {
        &["WH", "WOM", "BK"]
    }

    crate::impl_prefixes_pattern!();

    /// Ruby `initialize` の `@round_type = RoundType::CEIL`。
    fn round_type(&self) -> crate::enums::RoundType {
        crate::enums::RoundType::Ceil
    }

    /// Ruby `Warhammer4#result_1d100`。
    fn result_1d100(
        &self,
        total: crate::Int,
        _dice_total: i64,
        cmp_op: CmpOp,
        target: Target,
    ) -> Option<CheckOutcome> {
        // Ruby: return Result.nothing if target == '?'
        let Target::Number(target) = target else {
            return Some(CheckOutcome::Nothing);
        };
        check_1d100(total, cmp_op, target).map(|r| CheckOutcome::Result(Box::new(r)))
    }

    /// Ruby `Warhammer4#eval_game_system_specific_command`。
    fn eval_game_system_specific_command(
        &self,
        command: &str,
        rng: &mut Randomizer,
    ) -> Result<Option<SpecificCommandOutput>, EvalError> {
        // Ruby は `command.upcase` に対してマッチさせるが、`enabled_upcase_input` が
        // 既定の true なので、ここへ来る時点で command は大文字化済み。
        let output = if let Some(output) = roll_critical_table(command, rng)? {
            output
        } else if let Some(output) = roll_attack(command, rng)? {
            output
        } else if let Some(output) = roll_wrath_of_god_table(command, rng)? {
            output
        } else if let Some(output) = roll_tables(command, rng)? {
            output
        } else {
            return Ok(None);
        };

        Ok(Some(SpecificCommandOutput::text(output)))
    }
}

