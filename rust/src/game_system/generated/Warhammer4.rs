/// Ruby `Warhammer4#result_1d100` のうち `Result` を返す部分。
///
/// `result_1d100`（トレイトのフック）と `roll_attack` の両方から呼ぶため、
/// 目標値 `"?"`（Ruby の `Result.nothing`）の分岐は呼び出し側に残してある。
fn check_1d100(total: crate::Int, cmp_op: CmpOp, target: crate::Int) -> Option<EvalResult> {
    // Ruby: return nil unless cmp_op == :<=
    if cmp_op != CmpOp::Le {
        return None;
    }

    // SL（成功度）は十の位同士の差
    let t10 = floor_div(total.clone(), crate::Int::from(10));
    let d10 = floor_div(target.clone(), crate::Int::from(10));
    let mut sl: crate::Int = d10 - t10;

    if total <= crate::Int::from(5) && sl < crate::Int::ONE {
        // 自動成功時のSLは最低でも1
        sl = crate::Int::ONE;
    } else if total >= crate::Int::from(96) && sl > crate::Int::from(-1) {
        // 自動失敗時のSLは最大でも-1
        sl = crate::Int::from(-1);
    }

    let mut result = if total <= crate::Int::from(5) {
        EvalResult::success("自動成功")
    } else if total >= crate::Int::from(96) {
        EvalResult::failure("自動失敗")
    } else if total <= target {
        EvalResult::success("成功")
    } else {
        EvalResult::failure("失敗")
    };

    // Ruby: format("(SL%+d)", sl)。ただし失敗側の SL0 は "+0" ではなく "-0" と書く
    let sl_text = if sl == crate::Int::ZERO && total > target {
        "(SL-0)".to_owned()
    } else {
        format!("(SL{sl:+})")
    };

    let detail = result_detail(sat_i64(&sl), sat_i64(&total), sat_i64(&target));
    result.text.push_str(&format!("{sl_text} ＞ {detail}"));

    Some(result)
}

/// Ruby `Warhammer4#result_detail`。SLから成功ランク名を決める。
fn result_detail(sl: i64, total: i64, target: i64) -> &'static str {
    if sl == 0 {
        if total <= 5 {
            "小成功"
        } else if total >= 96 {
            "小失敗"
        } else if total <= target {
            "小成功"
        } else {
            "小失敗"
        }
    } else if sl >= 6 {
        "超大成功"
    } else if sl >= 4 {
        "大成功"
    } else if sl >= 2 {
        "成功"
    } else if sl > 0 {
        "小成功"
    } else if sl >= -1 {
        "小失敗"
    } else if sl >= -3 {
        "失敗"
    } else if sl >= -5 {
        "大失敗"
    } else {
        // Ruby: else # sl <= -6
        "超大失敗"
    }
}

