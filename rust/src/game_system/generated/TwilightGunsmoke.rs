/// Ruby `#check_roll` の正規表現
/// `/^2D6([+\-\d]*)>=(\d+)(\[(\d+)?(,(\d+))?\])?$/i`。
fn check_roll_re() -> &'static Regex {
    static RE: OnceLock<Regex> = OnceLock::new();
    RE.get_or_init(|| {
        Regex::new(r"(?i)^2D6([+\-\d]*)>=(\d+)(\[(\d+)?(,(\d+))?\])?$").expect("valid regex")
    })
}

/// Ruby `TwilightGunsmoke#check_roll`。
fn check_roll(command: &str, rng: &mut Randomizer) -> Result<Option<String>, EvalError> {
    let Some(m) = check_roll_re().captures(command) else {
        return Ok(None);
    };

    // Ruby: m[1] は `*` なので常に（空文字列でも）マッチする。
    // `ArithmeticEvaluator.eval("")` はパースに失敗して 0 になる。
    let modify_number = arithmetic::eval(&m[1], RoundType::Floor)?
        .as_ref()
        .map(crate::randomizer::sat_i64)
        .unwrap_or(0);
    let target: i64 = m[2].parse().unwrap_or(0);
    let critical: i64 = m.get(4).and_then(|c| c.as_str().parse().ok()).unwrap_or(12);
    let fumble: i64 = m.get(6).and_then(|c| c.as_str().parse().ok()).unwrap_or(2);

    let mut dice_list = rng.roll_barabara(2, 6)?;
    dice_list.sort_unstable();
    let dice_value: i64 = dice_list.iter().sum();
    let dice_str = dice_list
        .iter()
        .map(|d| d.to_string())
        .collect::<Vec<_>>()
        .join(",");

    let total = dice_value + modify_number;

    let result = if dice_value >= critical {
        "自動成功"
    } else if dice_value <= fumble {
        "自動失敗"
    } else if total >= target {
        "成功"
    } else {
        "失敗"
    };

    let sequence = [
        format!("({command})"),
        format!(
            "{dice_value}[{dice_str}]{}",
            format::modifier(&crate::Int::from(modify_number))
        ),
        total.to_string(),
        result.to_string(),
    ];

    Ok(Some(sequence.join(" ＞ ")))
}

