/// Ruby `MonotoneMuseum#check_roll`。
fn check_roll(
    sys: &SystemTables,
    command: &str,
    rng: &mut Randomizer,
) -> Result<Option<EvalResult>, EvalError> {
    static RE: OnceLock<Regex> = OnceLock::new();
    let re = RE.get_or_init(|| {
        Regex::new(r"(?i)^(\d+)D6([+\-\d]*)>=(\?|\d+)(\[(\d+)?(,(\d+))?\])?$").expect("valid regex")
    });
    let Some(m) = re.captures(command) else {
        return Ok(None);
    };

    let Some(dice_count) = m.get(1).and_then(|x| x.as_str().parse::<i64>().ok()) else {
        return Ok(None);
    };
    // Ruby: m[2] ? ArithmeticEvaluator.eval(m[2]) : 0（空文字列は 0）
    let modify_number = match m.get(2) {
        Some(x) => arithmetic::eval(x.as_str(), RoundType::Floor)?
            .as_ref()
            .map(crate::randomizer::sat_i64)
            .unwrap_or(0),
        None => 0,
    };
    // Ruby: m[3].to_i（"?" は 0）
    let target = m
        .get(3)
        .and_then(|x| x.as_str().parse::<i64>().ok())
        .unwrap_or(0);
    let critical = m
        .get(5)
        .and_then(|x| x.as_str().parse::<i64>().ok())
        .unwrap_or(12);
    let fumble = m
        .get(7)
        .and_then(|x| x.as_str().parse::<i64>().ok())
        .unwrap_or(2);

    let mut dice_list = rng.roll_barabara(dice_count, 6)?;
    dice_list.sort_unstable();
    let dice_value: i64 = dice_list.iter().sum();
    let dice_str = dice_list
        .iter()
        .map(|d| d.to_string())
        .collect::<Vec<_>>()
        .join(",");
    let total = dice_value + modify_number;

    let (mut result, result_text) = if dice_value <= fumble {
        (EvalResult::fumble(""), Some(sys.automatic_failure))
    } else if dice_value >= critical {
        (EvalResult::critical(""), Some(sys.automatic_success))
    } else if target == 0 {
        // Ruby: Result.success(nil)
        (EvalResult::success(""), None)
    } else if total >= target {
        (EvalResult::success(""), Some(sys.success))
    } else {
        (EvalResult::failure(""), Some(sys.failure))
    };

    let mut sequence = vec![
        format!("({command})"),
        format!(
            "{dice_value}[{dice_str}]{}",
            format::modifier(&crate::Int::from(modify_number))
        ),
        total.to_string(),
    ];
    if let Some(text) = result_text {
        sequence.push(text.to_owned());
    }

    result.text = sequence.join(" ＞ ");
    Ok(Some(result))
}

/// Ruby `MonotoneMuseum#eval_game_system_specific_command`。
pub(crate) fn eval_specific_command(
    sys: &SystemTables,
    command: &str,
    rng: &mut Randomizer,
) -> Result<Option<SpecificCommandOutput>, EvalError> {
    if let Some(result) = check_roll(sys, command, rng)? {
        return Ok(Some(SpecificCommandOutput::result(result)));
    }
    Ok(table_helpers::roll_table(command, sys.tables, rng)?.map(SpecificCommandOutput::text))
}

