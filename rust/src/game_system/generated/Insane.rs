fn interpolate_skill(template: &str, skill_text: &str) -> String {
    template.replace("%{skill}", skill_text)
}

/// Ruby `Insane#get_badend_table`。
fn get_badend_table(sys: &SystemTables, rng: &mut Randomizer) -> Result<(String, i64), EvalError> {
    let total_n = rng.roll_sum(2, 6)?;
    let index = total_n - 2;
    let Some(item) = usize::try_from(index)
        .ok()
        .and_then(|i| sys.bet_items.get(i).copied())
    else {
        return Ok(("1".to_owned(), 0));
    };
    // 3 と 11（0始まりで 1 と 9）は RTT を振る。プレースホルダが無くても乱数は消費する。
    let output = if index == 1 || index == 9 {
        let skill = sys.rtt.roll_skill(rng)?;
        let skill_text = skill
            .map(|s| s.format_with(DEFAULT_SKILL_FORMAT))
            .unwrap_or_default();
        interpolate_skill(item, &skill_text)
    } else {
        item.to_owned()
    };
    Ok((output, total_n))
}

/// Ruby `Insane#get_interim_reference_number`。
fn get_interim_reference_number(rng: &mut Randomizer) -> Result<(String, String), EvalError> {
    let number = rng.roll_once(6)?;
    let mut total_n = number.to_string();
    let counts = if number <= 4 {
        number + 5
    } else if number == 5 {
        4
    } else {
        3
    };

    let mut output = String::new();
    for _ in 0..counts {
        let key = rng.roll_d66(D66SortType::Asc)?;
        let character = get_table_by_number(key, IRN_CHARS);
        output.push_str(character);
        total_n.push(',');
        total_n.push_str(&key.to_string());
    }
    Ok((output, total_n))
}

/// Ruby `Insane#result_2d6`。
pub(crate) fn check_result_2d6(
    sys: &SystemTables,
    total: crate::Int,
    dice_total: i64,
    cmp_op: CmpOp,
    target: Target,
) -> Option<CheckOutcome> {
    if cmp_op != CmpOp::Ge {
        return None;
    }
    if dice_total <= 2 {
        Some(CheckOutcome::Result(Box::new(EvalResult::fumble(
            sys.fumble,
        ))))
    } else if dice_total >= 12 {
        Some(CheckOutcome::Result(Box::new(EvalResult::critical(
            sys.special,
        ))))
    } else if matches!(target, Target::Question) {
        Some(CheckOutcome::Nothing)
    } else {
        let Target::Number(target) = target else {
            return None;
        };
        if total >= target {
            Some(CheckOutcome::Result(Box::new(EvalResult::success(
                sys.success,
            ))))
        } else {
            Some(CheckOutcome::Result(Box::new(EvalResult::failure(
                sys.failure,
            ))))
        }
    }
}

/// Ruby `Insane#eval_game_system_specific_command`。
pub(crate) fn eval_specific_command(
    sys: &SystemTables,
    command: &str,
    rng: &mut Randomizer,
) -> Result<Option<SpecificCommandOutput>, EvalError> {
    match command {
        "BET" => {
            let (output, total_n) = get_badend_table(sys, rng)?;
            Ok(Some(SpecificCommandOutput::text(format!(
                "{}({}) ＞ {output}",
                sys.bet_name, total_n
            ))))
        }
        "IRN" => {
            let (output, total_n) = get_interim_reference_number(rng)?;
            Ok(Some(SpecificCommandOutput::text(format!(
                "{}({total_n}) ＞ {output}",
                sys.irn_name
            ))))
        }
        _ => {
            if let Some(text) = sys.rtt.roll_command(rng, command)? {
                return Ok(Some(SpecificCommandOutput::text(text)));
            }
            Ok(table_helpers::roll_table(command, sys.tables, rng)?
                .map(SpecificCommandOutput::text))
        }
    }
}

